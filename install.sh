#!/usr/bin/env bash
# Install Flappy CDN live dashboard on the CDN host (LXC/VM/bare metal).
# LAN-only UI on :8090 — tails nginx access log + live TCP via ss.
#
# Usage:
#   sudo ./install.sh
#   sudo ./install.sh --with-nginx --proxy-ip 192.168.1.226
#   sudo ./install.sh --access-log /var/log/nginx/cdn.flappy.su.access.log --port 8090
#   sudo ./install.sh --uninstall
#
set -euo pipefail

PREFIX="${CDN_DASH_PREFIX:-/opt/cdn-dashboard}"
ENV_FILE="${CDN_DASH_ENV_FILE:-/etc/default/cdn-dashboard}"
SERVICE_NAME="cdn-dashboard"
UNIT_DST="/etc/systemd/system/${SERVICE_NAME}.service"

DASH_HOST="${CDN_DASH_HOST:-0.0.0.0}"
DASH_PORT="${CDN_DASH_PORT:-8090}"
ACCESS_LOG="${CDN_ACCESS_LOG:-/var/log/nginx/cdn.flappy.su.access.log}"
NGINX_PORT="${CDN_NGINX_PORT:-8080}"
DASH_ALLOW="${CDN_DASH_ALLOW:-192.168.,10.,127.0.0.1,::1}"
PROXY_IP="${CDN_PROXY_IP:-}"
WITH_NGINX=0
SKIP_START=0
UNINSTALL=0

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

usage() {
  cat <<EOF
Flappy CDN live dashboard installer

Options:
  --prefix DIR           Install dir (default: /opt/cdn-dashboard)
  --port N               Dashboard port (default: 8090)
  --host ADDR            Bind address (default: 0.0.0.0)
  --access-log PATH      Nginx access log to tail
  --nginx-port N         CDN nginx port for live TCP stats (default: 8080)
  --allow PREFIXES       Comma-separated allowed client IP prefixes (LAN)
  --proxy-ip IP          Reverse-proxy IP for nginx real_ip (e.g. NPM)
  --with-nginx           Patch nginx log_format + access_log + optional real_ip
  --skip-start           Install files only
  --uninstall            Remove service and /opt files
  -h, --help             Help

Env: CDN_DASH_HOST CDN_DASH_PORT CDN_ACCESS_LOG CDN_NGINX_PORT
     CDN_DASH_ALLOW CDN_PROXY_IP CDN_DASH_PREFIX
EOF
}

log()  { printf '==> %s\n' "$*"; }
warn() { printf 'WARN: %s\n' "$*" >&2; }
die()  { printf 'ERR: %s\n' "$*" >&2; exit 1; }

need_root() { [[ "$(id -u)" -eq 0 ]] || die "Run as root: sudo ./install.sh"; }
have() { command -v "$1" >/dev/null 2>&1; }

parse_args() {
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --prefix) PREFIX="$2"; shift 2 ;;
      --port) DASH_PORT="$2"; shift 2 ;;
      --host) DASH_HOST="$2"; shift 2 ;;
      --access-log) ACCESS_LOG="$2"; shift 2 ;;
      --nginx-port) NGINX_PORT="$2"; shift 2 ;;
      --allow) DASH_ALLOW="$2"; shift 2 ;;
      --proxy-ip) PROXY_IP="$2"; shift 2 ;;
      --with-nginx) WITH_NGINX=1; shift ;;
      --skip-start) SKIP_START=1; shift ;;
      --uninstall) UNINSTALL=1; shift ;;
      -h|--help) usage; exit 0 ;;
      *) die "Unknown arg: $1" ;;
    esac
  done
}

uninstall() {
  need_root
  log "Stopping ${SERVICE_NAME}"
  systemctl stop "${SERVICE_NAME}" 2>/dev/null || true
  systemctl disable "${SERVICE_NAME}" 2>/dev/null || true
  rm -f "${UNIT_DST}"
  systemctl daemon-reload 2>/dev/null || true
  rm -rf "${PREFIX}"
  rm -f "${ENV_FILE}"
  log "Removed ${PREFIX}, unit, ${ENV_FILE}"
}

install_python() {
  if have python3; then
    log "python3: $(python3 --version 2>&1)"
    return
  fi
  log "Installing python3"
  if have apt-get; then
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -y
    apt-get install -y python3
  elif have dnf; then
    dnf install -y python3
  elif have yum; then
    yum install -y python3
  elif have apk; then
    apk add --no-cache python3
  else
    die "python3 not found and no known package manager"
  fi
}

install_ss() {
  if have ss; then return; fi
  log "Installing iproute2 (ss)"
  if have apt-get; then
    export DEBIAN_FRONTEND=noninteractive
    apt-get install -y iproute2
  elif have dnf; then
    dnf install -y iproute
  elif have yum; then
    yum install -y iproute
  elif have apk; then
    apk add --no-cache iproute2
  else
    warn "ss not found — live stream speeds will be empty"
  fi
}

copy_files() {
  log "Installing into ${PREFIX}"
  mkdir -p "${PREFIX}"
  [[ -f "${SCRIPT_DIR}/server.py" ]] || die "server.py missing next to install.sh"
  [[ -f "${SCRIPT_DIR}/cdn-dashboard.service" ]] || die "cdn-dashboard.service missing"
  install -m 0755 "${SCRIPT_DIR}/server.py" "${PREFIX}/server.py"
  install -m 0644 "${SCRIPT_DIR}/cdn-dashboard.service" "${UNIT_DST}"
  if [[ "${PREFIX}" != "/opt/cdn-dashboard" ]]; then
    sed -i "s|/opt/cdn-dashboard|${PREFIX}|g" "${UNIT_DST}"
  fi
  # Ensure EnvironmentFile is present
  if ! grep -q "EnvironmentFile=-${ENV_FILE}" "${UNIT_DST}" \
     && ! grep -q 'EnvironmentFile=-/etc/default/cdn-dashboard' "${UNIT_DST}"; then
    sed -i "/\[Service\]/a EnvironmentFile=-${ENV_FILE}" "${UNIT_DST}"
  fi
}

write_env() {
  log "Writing ${ENV_FILE}"
  mkdir -p "$(dirname "${ENV_FILE}")"
  cat > "${ENV_FILE}" <<EOF
# Generated by flappy-cdn-dashboard install.sh
CDN_DASH_HOST=${DASH_HOST}
CDN_DASH_PORT=${DASH_PORT}
CDN_ACCESS_LOG=${ACCESS_LOG}
CDN_NGINX_PORT=${NGINX_PORT}
CDN_DASH_ALLOW=${DASH_ALLOW}
EOF
  chmod 0644 "${ENV_FILE}"
}

patch_nginx() {
  [[ "${WITH_NGINX}" -eq 1 ]] || return 0
  if ! have nginx; then
    warn "nginx not installed — skip --with-nginx"
    return 0
  fi
  log "Patching nginx (best-effort)"
  export ACCESS_LOG PROXY_IP NGINX_PORT
  python3 - <<'PY'
import os, re, subprocess
from pathlib import Path

access_log = os.environ["ACCESS_LOG"]
proxy_ip = os.environ.get("PROXY_IP") or ""
nginx_port = os.environ.get("NGINX_PORT") or "8080"

conf = Path("/etc/nginx/nginx.conf")
if not conf.is_file():
    raise SystemExit("no /etc/nginx/nginx.conf")

t = conf.read_text()
if "log_format cdn_timed" not in t:
    snip = (
        "\n\t# Flappy CDN dashboard: request_time for completed transfer speeds\n"
        "\tlog_format cdn_timed '$remote_addr - $remote_user [$time_local] '\n"
        "\t                     '\"$request\" $status $body_bytes_sent '\n"
        "\t                     '\"$http_referer\" \"$http_user_agent\" '\n"
        "\t                     '$request_time xff=\"$http_x_forwarded_for\"';\n"
    )
    m = re.search(r"http\s*\{", t)
    if not m:
        raise SystemExit("no http { in nginx.conf")
    nl = t.find("\n", m.end() - 1)
    conf.write_text(t[: nl + 1] + snip + t[nl + 1 :])
    print("inserted log_format cdn_timed")
else:
    print("log_format cdn_timed already present")

candidates = []
for base in (Path("/etc/nginx/sites-enabled"), Path("/etc/nginx/conf.d")):
    if base.is_dir():
        candidates.extend(p for p in sorted(base.iterdir()) if p.is_file())

any_site = False
for site in candidates:
    original = site.read_text(errors="replace")
    txt = original
    plain = f"access_log {access_log};"
    timed = f"access_log {access_log} cdn_timed;"
    if plain in txt:
        txt = txt.replace(plain, timed)
        print(f"{site.name}: access_log -> cdn_timed")
        any_site = True
    elif re.search(rf"access_log\s+{re.escape(access_log)}\s+cdn_timed\s*;", txt):
        print(f"{site.name}: already cdn_timed")
        any_site = True
    elif access_log in txt:
        txt2, n = re.subn(
            rf"access_log\s+{re.escape(access_log)}\s*;",
            timed,
            txt,
        )
        if n:
            txt = txt2
            print(f"{site.name}: access_log format -> cdn_timed")
            any_site = True

    if proxy_ip and "set_real_ip_from" not in txt:
        if "server {" in txt and (
            access_log in original
            or f"listen {nginx_port}" in original
            or "cdn." in original.lower()
        ):
            block = (
                f"\n    # Client IP behind reverse proxy (NPM/etc.)\n"
                f"    set_real_ip_from {proxy_ip};\n"
                f"    set_real_ip_from 192.168.0.0/16;\n"
                f"    set_real_ip_from 10.0.0.0/8;\n"
                f"    real_ip_header X-Forwarded-For;\n"
                f"    real_ip_recursive on;\n"
            )
            txt2, n = re.subn(r"(server_name\s+[^;]+;)", r"\1\n" + block, txt, count=1)
            if not n:
                txt2, n = re.subn(r"(server\s*\{)", r"\1\n" + block, txt, count=1)
            if n:
                txt = txt2
                print(f"{site.name}: real_ip from {proxy_ip}")

    if txt != original:
        site.write_text(txt)

if not any_site:
    print(
        f"NOTE: could not auto-wire access_log {access_log}. "
        "Set manually: access_log <path> cdn_timed;"
    )

r = subprocess.run(["nginx", "-t"], capture_output=True, text=True)
print(((r.stderr or "") + (r.stdout or "")).strip())
if r.returncode != 0:
    raise SystemExit("nginx -t failed")
subprocess.check_call(["systemctl", "reload", "nginx"])
print("nginx reloaded")
PY
}

enable_service() {
  if [[ "${SKIP_START}" -eq 1 ]]; then
    log "Skip start (--skip-start)"
    return
  fi
  if ! have systemctl; then
    warn "no systemctl — run: python3 ${PREFIX}/server.py"
    return
  fi
  systemctl daemon-reload
  systemctl enable "${SERVICE_NAME}"
  systemctl restart "${SERVICE_NAME}"
  sleep 1
  systemctl --no-pager --full status "${SERVICE_NAME}" | head -20 || true
}

health_check() {
  local url="http://127.0.0.1:${DASH_PORT}/health"
  if have curl; then
    if out=$(curl -fsS -m 3 "${url}" 2>/dev/null); then
      log "Health OK ${url} (${out//$'\n'/})"
    else
      warn "Health check failed: ${url}"
      journalctl -u "${SERVICE_NAME}" -n 30 --no-pager || true
    fi
  fi
}

print_done() {
  cat <<EOF

----------------------------------------------------------
  Flappy CDN dashboard installed

  UI (LAN):     http://<this-host-ip>:${DASH_PORT}/
  API:          http://<this-host-ip>:${DASH_PORT}/api/live
  Files:        ${PREFIX}
  Env:          ${ENV_FILE}
  Unit:         ${SERVICE_NAME}.service

  Access log:   ${ACCESS_LOG}
  Nginx port:   ${NGINX_PORT}
  Allow:        ${DASH_ALLOW}

  systemctl status ${SERVICE_NAME}
  journalctl -u ${SERVICE_NAME} -f

  Behind NPM: send X-Forwarded-For; disable response buffering
  for large package downloads.
----------------------------------------------------------
EOF
}

main() {
  parse_args "$@"
  if [[ "${UNINSTALL}" -eq 1 ]]; then
    uninstall
    exit 0
  fi
  need_root
  install_python
  install_ss
  copy_files
  write_env
  patch_nginx
  enable_service
  health_check
  print_done
}

main "$@"
